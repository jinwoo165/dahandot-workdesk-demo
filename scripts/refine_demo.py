from pathlib import Path
import base64,hashlib,json,re,subprocess
root=Path(__file__).resolve().parents[1]
p=root/'index.html'
s=p.read_text()
s=s.replace('저장됐습니다. 다음 갱신 때 다한닷이 확인합니다.','현재 화면에만 보관했습니다. 서버 전송과 AI 자동 처리는 하지 않습니다.')
s=s.replace('다한닷 확인 대기','현재 화면에 보관')
s=s.replace('모든 대화 확인','업무 대화 기록')
s=s.replace('대화 확인 대기','입력한 대화')
s=s.replace('확인 대기 ${pending}건','화면 보관 ${pending}건')
s=s.replace('두레이 즐겨찾기 · 일정 30일','독립 공개본 · 운영 계정 미연결')
s=s.replace('업무 갱신 때 필요한 원문을 확인해 추가합니다. 필요 없는 바로가기는 삭제하세요.','각 서비스의 공식 진입점입니다. 로그인 후 본인의 업무 공간을 선택하세요.')
s=s.replace('이것은 당시의 기록입니다. 현재 업무 상태와 다를 수 있습니다.','실제 업무 내용을 바탕으로 구성한 흐름 기록입니다. 표시 날짜·상태 전이는 확정된 감사 이력이 아닙니다.')
s=s.replace('저장된 상태·메모 변경','업무 흐름·메모 기록')
s=s.replace('저장된 상태·메모','업무 흐름·메모')
s=s.replace('공정관리 시스템 업무 협의','공정관리 시스템 업무 회의')
s=s.replace('OneDrive 기반 공무 업무 폴더 셋업','OneDrive 기반 공무 업무폴더 안내 정리')
s=s.replace('해당 업무의 대화에 복원을 요청하세요.','해당 업무를 열어 지난 기록을 확인하세요.')
s=s.replace('진척과 생각을 편하게 남기세요. 필요한 정리는 다한닷이 이어갑니다.','업무별 대화와 정리된 후속 조치를 확인하세요. 입력은 현재 화면에만 남습니다.')
script=re.search(r'<script>([\s\S]*)</script>',s).group(1)
h=base64.b64encode(hashlib.sha256(script.encode()).digest()).decode()
s=re.sub(r"script-src 'sha256-[^']+'", "script-src 'sha256-"+h+"'",s)
p.write_text(s)
(root/'build.js').write_text(script)
subprocess.run(['node','--check',str(root/'build.js')],check=True)
report=json.loads((root/'build-report.json').read_text())
report.update(bytes=len(s.encode()),sha256=hashlib.sha256(s.encode()).hexdigest())
(root/'build-report.json').write_text(json.dumps(report,indent=2))
print(json.dumps(report,indent=2))
